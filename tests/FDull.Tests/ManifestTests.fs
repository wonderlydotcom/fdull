    let private run root (arguments: string list) =
        let start = ProcessStartInfo("dotnet", WorkingDirectory = root)

        for argument in arguments do
            start.ArgumentList.Add argument

        start.Environment["DOTNET_GCHeapHardLimit"] <- "80000000"
        start.Environment["MSBUILDDISABLENODEREUSE"] <- "1"

        match
            SafetyProcess.run
                { Milliseconds = 180000
                  OutputCharacters = 1048576
                  WorkingSetBytes = 2147483648L }
                start
                ""
        with
        | Ok result -> result
        | Error error -> failwith error

    let private built root arguments =
        let result = run root arguments
        Assert.True(result.ExitCode = 0, result.Error + result.Output)

    let private cli =
        Path.GetFullPath(
            Path.Combine(AppContext.BaseDirectory, "../../../../../src/FDull.Tool/bin/Release/net10.0/FDull.Cli.dll")
        )

    let private donor (properties: string) (items: string) =
        "<Project Sdk=\"Microsoft.NET.Sdk\"><PropertyGroup><FSharpCoreImplicitPackageVersion>10.0.100</FSharpCoreImplicitPackageVersion>"
        + properties
        + "</PropertyGroup><ItemGroup>"
        + items
        + "</ItemGroup></Project>"

    /// A Bazel-style execution root: the workspace `pkg` with a library and the tests that reference
    /// it, the entry point the tests share from outside the workspace, rules_dotnet's version file, and
    /// argument files and manifests under `out`. Two MSBuild projects over the same sources supply
    /// what a Bazel build would: the library's compiled and reference assemblies, and the real
    /// FSharp.Core 10.0.100 and framework references. `out/manifest.json` spells every path in full;
    /// `out/relative/manifest.json` spells paths under the execution root relative to it, as Bazel does.
    let private withWorkspace action =
        withDirectory (fun execroot ->
            let under (path: string) = Path.Combine(execroot, path)

            write execroot "global.json" "{\"sdk\":{\"version\":\"10.0.403\",\"rollForward\":\"disable\"}}"
            write execroot "Directory.Build.props" (Project.defaults ())

            write
                execroot
                "NuGet.config"
                "<configuration><packageSources><clear/><add key=\"nuget.org\" value=\"https://api.nuget.org/v3/index.json\"/></packageSources></configuration>"

            workspace execroot
            write execroot versionFile (versionText "0.1.0.0" "0.1.0")
            write execroot "donor/Lib/Lib.fsproj" (donor "" "<Compile Include=\"../../pkg/src/Lib.fs\"/>")

            write
                execroot
                "donor/Tests/Tests.fsproj"
                (donor
                    "<OutputType>Exe</OutputType>"
                    ("<ProjectReference Include=\"../Lib/Lib.fsproj\"/><Compile Include=\"../../pkg/tests/LibTests.fs\"/>"
                     + "<Compile Include=\"../../"
                     + sharedFile
                     + "\"/>"))

            built execroot [ "restore"; "donor/Tests/Tests.fsproj"; "-m:1"; "-nr:false" ]

            built
                execroot
                [ "build"
                  "donor/Lib/Lib.fsproj"
                  "-c"
                  "Release"
                  "--no-restore"
                  "-m:1"
                  "--disable-build-servers" ]

            let references project =
                match Workspace.export execroot project with
                | Ok invocation -> invocation.References
                | Error error -> failwith error

            let libraryOutput = under "donor/Lib/obj/Release/net10.0"
            let libraryReferences = references "donor/Lib/Lib.fsproj"
            let testReferences = references "donor/Tests/Tests.fsproj"
            Assert.Contains(libraryOutput + "/ref/Lib.dll", testReferences)

            for directory, relative in [ "out", false; "out/relative", true ] do
                // Bazel spells a path under the execution root relative to it.
                let spell (path: string) =
                    if relative && path.StartsWith(execroot, StringComparison.Ordinal) then
                        Path.GetRelativePath(execroot, path)
                    else
                        path

                let arguments name lines =
                    let file = directory + "/" + name + ".params"
                    write execroot file (String.concat "\n" lines + "\n")
                    spell (under file)

                let manifest: WorkspaceManifestDocument =
                    { Version = 1
                      Projects =
                        [ { Name = ":Lib"
                            Arguments =
                              arguments
                                  "Lib"
                                  (rulesDotnetArguments
                                      "library"
                                      (spell libraryOutput)
                                      "Lib"
                                      (libraryReferences |> List.map spell)
                                      [ spell (under versionFile); spell (under "pkg/src/Lib.fs") ]) }
                          { Name = ":tests"
                            Arguments =
                              arguments
                                  "tests"
                                  (rulesDotnetArguments
                                      "exe"
                                      (spell (under "bazel-out/k8-opt/bin/pkg/tests/net10.0"))
                                      "tests"
                                      (testReferences |> List.map spell)
                                      [ spell (under "pkg/tests/LibTests.fs"); spell (under sharedFile) ]) } ]
                      Files = inventory |> List.map (fun file -> spell (under ("pkg/" + file))) }

                write execroot (directory + "/manifest.json") (Codec.encode manifest)

            action execroot)

    /// Seed a mutable binding into the library of the workspace at `root` and pin its new fingerprint,
    /// so only the rule fails.
    let private seed (root: string) =
        write root "src/Lib.fs" "module Lib\n\nlet increment value = value + 1\nlet mutable count = 0\n"
        save root policy

    [<Fact>]
    let ``a Bazel workspace passes, fails on a seeded violation and reports its derived edge`` () =
        withWorkspace (fun execroot ->
            let root = Path.Combine(execroot, "pkg")
            let manifest = Path.Combine(execroot, "out/manifest.json")
            let passed = Workspace.checkManifest root manifest
            Assert.True(passed.Complete, Codec.encode passed)
            Assert.Equal(0, passed.ExitCode)
            Assert.Equal(0, passed.Cached)
            Assert.Empty(passed.Projects |> List.collect _.Report.Diagnostics)

            Assert.Equal<(string * string list) list>(
                [ Path.Combine(root, ":Lib"), []; Path.Combine(root, ":tests"), [ ":Lib" ] ],
                passed.Projects
                |> List.map (fun project -> project.Project, project.ProjectReferences)
            )

            // The library analyzed rules_dotnet's version file and the tests the shared entry point.
            for project, outside in [ ":Lib", versionFile; ":tests", sharedFile ] do
                Assert.Contains(
                    passed.Projects,
                    fun report ->
                        report.Project = Path.Combine(root, project)
                        && report.Report.Sources
                           |> List.exists (fun source -> source.Path = Path.Combine(execroot, outside))
                )

            // The build system keeps the only cache.
            Assert.False(Directory.Exists(Path.Combine(root, ".fdull")))

            let reviewed = Workspace.reviewManifest root manifest
            Assert.True(reviewed.AnalysisComplete, WorkspaceReview.format reviewed)
            Assert.Equal(0, reviewed.ExitCode)

            // Without a manifest, a version-three policy blocks every MSBuild command.
            let unsupported = Workspace.check root
            Assert.False unsupported.Complete
            Assert.Equal(3, unsupported.ExitCode)
            Assert.StartsWith(wellFormed, Assert.Single unsupported.Errors)
            Assert.Equal(3, (Workspace.review root).ExitCode)
            rejects "BUILD003" (fun () -> Project.verify root |> ignore)

            // An edge the invocations show and the policy does not declare blocks.
            save
                root
                { policy with
                    Projects = policy.Projects |> List.map (fun project -> { project with References = [] }) }

            let undeclared = Workspace.checkManifest root manifest
            Assert.Equal(3, undeclared.ExitCode)
            Assert.StartsWith("ARCH001:", Assert.Single undeclared.Errors)

            // The shared source is authored source of the tests: without its contracts it fails there.
            save root { policy with Capabilities = [] }
            let ungranted = Workspace.checkManifest root manifest
            Assert.True(ungranted.Complete, Codec.encode ungranted)
            Assert.Equal(1, ungranted.ExitCode)

            for diagnostic in ungranted.Projects |> List.collect _.Report.Diagnostics do
                Assert.Equal(Path.Combine(execroot, sharedFile), diagnostic.File)
                Assert.Equal("TEST", diagnostic.Profile)

            // A compiled source from outside the workspace that the policy does not declare blocks.
            save
                root
                { policy with
                    Capabilities = []
                    Sources = policy.Sources |> List.filter (fun source -> source.File <> "../" + sharedFile) }

            let stray = Workspace.checkManifest root manifest
            Assert.Equal(3, stray.ExitCode)

            Assert.StartsWith(
                ":tests: BUILD003: The build passed an F# source from outside",
                Assert.Single stray.Errors
            )

            // The shared source is pinned like any other: a change blocks until it is reviewed.
            save root policy
            write execroot sharedFile (sharedText + "\n")
            let drifted = Workspace.checkManifest root manifest
            Assert.Equal(3, drifted.ExitCode)

            Assert.Equal(
                "BUILD005: Source changed since its exact contracts were reviewed: ../"
                + sharedFile,
                Assert.Single drifted.Errors
            )

            write execroot sharedFile sharedText

            // One changed byte in the version file blocks its project.
            write execroot versionFile ((versionText "0.1.0.0" "0.1.0").Replace("do ()", "do ();"))
            let changed = Workspace.checkManifest root manifest
            Assert.Equal(3, changed.ExitCode)
            Assert.Contains(changed.Errors, fun error -> error.StartsWith(":Lib: BUILD003:", StringComparison.Ordinal))
            write execroot versionFile (versionText "0.1.0.0" "0.1.0")

            seed root
            let failed = Workspace.checkManifest root manifest
            Assert.True(failed.Complete, Codec.encode failed)
            Assert.Equal(1, failed.ExitCode)

            let diagnostics = failed.Projects |> List.collect _.Report.Diagnostics
            Assert.Contains(diagnostics, fun diagnostic -> diagnostic.Rule = "MUT001")

            for diagnostic in diagnostics do
                Assert.Equal(Path.Combine(root, "src/Lib.fs"), diagnostic.File)
                Assert.Equal(Path.Combine(root, ":Lib"), diagnostic.Project))

