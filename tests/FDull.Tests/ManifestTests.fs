            Assert.Equal(3, blocked.ExitCode)
            Assert.StartsWith("FDull lint: BLOCKED", blocked.Output)
            Assert.Contains(wellFormed, blocked.Error)
            Assert.Equal(blocked.Output, report ())

            for repeated in [ "--report"; "--manifest" ] do
                Assert.Equal(2, (lint [ repeated; "out/other.txt"; repeated; "out/other.txt" ]).ExitCode)

            Assert.False(File.Exists(Path.Combine(execroot, "out/other.txt"))))
