    [<Fact>]
    let ``a version three source may live outside the workspace under one bounded shortest path`` () =
        withDirectory (fun execroot ->
            workspace execroot
            let root = Path.Combine(execroot, "pkg")

            let shared (file: string) (changed: WorkspacePolicyDocument) =
                { changed with
                    Capabilities = []
                    Sources =
                        changed.Sources
                        |> List.map (fun source ->
                            if source.File = "../" + sharedFile then
                                { source with File = file }
                            else
                                source) }

            Assert.StartsWith(wellFormed, validated root policy)

            // A name that leaves the path, climbs inside it or is not a local path is no source.
            for file in
                [ "/" + sharedFile
                  "../tools/../" + sharedFile
                  "../tools/./entry/Main.fs"
                  "..\\" + sharedFile
                  "../"
                  ".." ] do
                Assert.Equal("BUILD005: Invalid workspace source assignment.", validated root (shared file policy))

            // One file has one name: the shortest path from the workspace. A longer spelling of the
            // shared file, or one that leads back into the workspace, would alias a reviewed source.
            for file in
                [ "../pkg/tests/LibTests.fs"
                  "../../"
                  + (Path.GetFileName execroot |> External.required "manifest-tests.fixture-name")
                  + "/"
                  + sharedFile ] do
                Assert.StartsWith(
                    "BUILD005: A source outside the workspace must be named by its shortest path",
                    validated root (shared file policy)
                )

            // Sixteen segments is the bound. Each nested workspace reaches the same shared file.
            let nested (depth: int) =
                let package = String.replicate (depth - 1) "d/" + "pkg"
                let directory = Path.Combine(execroot, package)
                write directory "BUILD.bazel" "# Fixture package.\n"
                write directory "src/Lib.fs" "module Lib\n"
                write directory "tests/LibTests.fs" "module LibTests\n"
                validated directory (shared (String.replicate depth "../" + sharedFile) policy)

            Assert.StartsWith(wellFormed, nested 16)
            Assert.Equal("BUILD005: Invalid workspace source assignment.", nested 17)

            // Versions one and two keep every source inside the workspace.
            let projects (version: int) (changed: WorkspacePolicyDocument) =
                { changed with
                    Version = version
                    Capabilities = []
                    Projects =
                        changed.Projects
                        |> List.map (fun project ->
                            { project with
                                File = project.File.Replace(":", "") + ".fsproj"
                                References =
                                    project.References |> List.map (fun name -> name.Replace(":", "") + ".fsproj") })
                    Sources =
                        changed.Sources
                        |> List.map (fun source ->
                            { source with
                                Project = source.Project.Replace(":", "") + ".fsproj" }) }

            Assert.Equal("BUILD005: Invalid workspace source assignment.", validated root (projects 1 policy))

            Assert.Equal(
                "BUILD005: Invalid workspace source assignment.",
                validated
                    root
                    { projects 2 policy with
                        Repository =
                            Some
                                { Root = ".."
                                  SharedInputs = []
                                  References = [] } }
            )

            // Without the shared source the same version-one policy is well formed, and the MSBuild
            // audit then finds no project files.
            Assert.StartsWith(
                "ARCH002:",
                validated
                    root
                    { projects 1 policy with
                        Sources =
                            (projects 1 policy).Sources
                            |> List.filter (fun source -> source.File <> "../" + sharedFile) }
            ))

    [<Fact>]
    let ``manifest export derives references and takes outside sources only by content or policy`` () =
        withDirectory (fun execroot ->
            workspace execroot
            let root = Path.Combine(execroot, "pkg")
            let under (path: string) = Path.Combine(execroot, path)
            let core = under "external/core/FSharp.Core.dll"
            let libraryOutput = under "bazel-out/k8-opt/bin/pkg/Lib/net10.0"
            let library = libraryOutput + "/Lib.dll"
            let libraryReference = libraryOutput + "/ref/Lib.dll"
            let testsOutput = under "bazel-out/k8-opt/bin/pkg/tests/net10.0"
            let libSource = under "pkg/src/Lib.fs"
            let testSource = under "pkg/tests/LibTests.fs"
            write execroot versionFile (versionText "0.1.0.0" "0.1.0")

            let libArguments =
                rulesDotnetArguments "library" libraryOutput "Lib" [ core ] [ under versionFile; libSource ]

            let testArguments references sources =
                rulesDotnetArguments "exe" testsOutput "tests" references sources

            let manifest (projects: (string * string list) list) : WorkspaceManifestDocument =
                { Version = 1
                  Projects =
                    projects
                    |> List.map (fun (name, arguments) ->
                        let file = name.Replace(":", "") + ".params"
                        write execroot file (String.concat "\n" arguments + "\n")
                        { Name = name; Arguments = under file })
                  Files = [] }

            let export changed lib test project =
                Workspace.exportManifest root changed (manifest [ ":Lib", lib; ":tests", test ]) project

            let exported lib test project =
                match export policy lib test project with
                | Ok invocation -> invocation
                | Error error -> failwith error

            let complete =
                testArguments [ libraryReference; core ] [ testSource; under sharedFile ]

            // The policy declares the shared source for the tests, so their compile may take it.
            let test = exported libArguments complete ":tests"
            Assert.Equal<string list>([ testSource; under sharedFile ], test.Sources)
            Assert.Empty test.Generated
            Assert.Equal<string list>([ libraryReference; core ], test.References)
            Assert.Equal<string list>([ ":Lib" ], test.ProjectReferences)
            Assert.Empty test.ImportedBuildInputs
            Assert.Contains("-o:" + testsOutput + "/tests.dll", test.Arguments)
            Assert.DoesNotContain(testSource, test.Arguments)
            Assert.Equal(Ok(), WorkspaceCompilerPolicy.validateFor 3 test.Arguments)

            let lib = exported libArguments complete ":Lib"
            Assert.Equal<string list>([ under versionFile; libSource ], lib.Sources)
            Assert.Equal<string list>([ under versionFile ], lib.Generated)
            Assert.Empty lib.ProjectReferences

            // A compiled output is evidence of an edge as much as a reference output; no output, no edge.
            Assert.Equal<string list>(
                [ ":Lib" ],
                (exported libArguments (testArguments [ library; core ] [ testSource ]) ":tests").ProjectReferences
            )

            Assert.Empty((exported libArguments (testArguments [ core ] [ testSource ]) ":tests").ProjectReferences)

            // The version strings are free within the reviewed pattern.
            write execroot versionFile (versionText "12.34.56.78" "12.34.56-rc.1+build.5")
