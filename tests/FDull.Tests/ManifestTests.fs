    let private edges = [ ":Lib", []; ":tests", [ ":Lib" ] ]

    let private rejects (rule: string) (action: unit -> unit) =
        let error = Assert.Throws<InvalidOperationException> action
        Assert.StartsWith(rule + ":", error.Message)

    let private blocks (result: Result<'a, string>) =
        match result with
        | Error message -> Assert.StartsWith("BUILD003:", message)
        | Ok _ -> failwith "An incomplete or unsupported manifest invocation was accepted."

    [<Fact>]
    let ``rules_dotnet arguments become an invocation only a version three policy accepts`` () =
        let directory = Path.GetFullPath "execroot"
        let under (path: string) = Path.GetFullPath(path, directory)
        let output = "bazel-out/k8-opt/bin/pkg/tests/net10.0"
        let core = "external/nuget.fsharp.core.v10.0.100/lib/netstandard2.1/FSharp.Core.dll"

        let rewritten =
            rulesDotnetArguments "exe" output "tests" [ core ] [ "pkg/tests/LibTests.fs"; sharedFile ]
            |> WorkspaceManifest.rewrite directory

        let sources = [ under "pkg/tests/LibTests.fs"; under sharedFile ]

        let flags =
            rewritten |> List.filter (fun argument -> not (List.contains argument sources))

        Assert.Equal<string list>(sources, rewritten |> List.filter (fun argument -> List.contains argument sources))

        for expected in
            [ "-o:" + under (output + "/tests.dll")
              "--pdb:" + under (output + "/tests.pdb")
              "--refout:" + under (output + "/ref/tests.dll")
              "--doc:" + under (output + "/tests.xml")
              "-r:" + under core
              "--warnaserror+"
              "--warn:5"
              "--define:NET10_0"
              "--define:NULLABLE" ] do
            Assert.Contains(expected, flags)

        // An absolute path stays where it points, and nothing else is rewritten.
        Assert.Equal<string list>(
            [ "-r:" + under core
              "--nowarn:3180"
              "--warnaserror-"
              "--out:"
              "--unknown"
              "notes.txt" ],
            WorkspaceManifest.rewrite
                directory
                [ "-r:" + under core
                  "/nowarn:3180"
                  "/warnaserror-"
                  "--out:"
                  "--unknown"
                  "notes.txt" ]
        )

        Assert.Equal(Ok(), WorkspaceCompilerPolicy.validateFor 3 flags)
        Assert.True(WorkspaceCompilerPolicy.validate flags |> Result.isError)

        for version in [ 1; 2 ] do
            Assert.True(WorkspaceCompilerPolicy.validateFor version flags |> Result.isError)

        let baseline = WorkspaceCompilerPolicy.required @ [ "--warnaserror" ]

        for extra in
            [ "--utf8output"
              "--nowin32manifest"
              "--nologo"
              "--debug-"
              "--pdb:a.pdb"
              "--refout:a.dll" ] do
            Assert.Equal(Ok(), WorkspaceCompilerPolicy.validateFor 3 (baseline @ [ extra ]))
            Assert.True(WorkspaceCompilerPolicy.validateFor 2 (baseline @ [ extra ]) |> Result.isError)
            Assert.True(WorkspaceCompilerPolicy.validate (baseline @ [ extra ]) |> Result.isError)

        // Bazel's default compilation mode and every other unknown or disabling setting stay rejected.
        for flag in
            [ "--debug+"
              "--optimize-"
              "--define:DEBUG"
              "--tailcalls-"
              "--nowarn:3180"
              "--warnaserror-"
              "--pdb:"
              "--refout:"
              "notes.txt" ] do
            Assert.True(WorkspaceCompilerPolicy.validateFor 3 (flags @ [ flag ]) |> Result.isError)

        for required in "--warnaserror+" :: WorkspaceCompilerPolicy.required do
            Assert.True(
                WorkspaceCompilerPolicy.validateFor 3 (flags |> List.filter ((<>) required))
                |> Result.isError
            )

    [<Fact>]
    let ``a version three target defines the symbols of net10.0 or of net11.0 and never both`` () =
        // The symbols rules_dotnet defines for each framework, after the rewrite to compiler spellings.
        let shared =
            WorkspaceCompilerPolicy.required
            @ [ "--warnaserror+"
                "--define:NET"
                "--define:NETCOREAPP"
                "--define:NETCOREAPP1_0_OR_GREATER"
                "--define:NETCOREAPP1_1_OR_GREATER"
                "--define:NETCOREAPP2_0_OR_GREATER"
                "--define:NETCOREAPP2_1_OR_GREATER"
                "--define:NETCOREAPP2_2_OR_GREATER"
                "--define:NETCOREAPP3_0_OR_GREATER"
                "--define:NETCOREAPP3_1_OR_GREATER"
                "--define:NET5_0_OR_GREATER"
                "--define:NET6_0_OR_GREATER"
                "--define:NET7_0_OR_GREATER"
                "--define:NET8_0_OR_GREATER"
                "--define:NET9_0_OR_GREATER"
                "--define:NET10_0_OR_GREATER"
                "--define:NULLABLE" ]

        let net10 = shared @ [ "--define:NET10_0" ]
        let net11 = shared @ [ "--define:NET11_0"; "--define:NET11_0_OR_GREATER" ]

        Assert.Equal<string list>(
            [ "--define:NET11_0"; "--define:NET11_0_OR_GREATER" ],
            WorkspaceManifest.rewrite (Path.GetFullPath "execroot") [ "-d:NET11_0"; "-d:NET11_0_OR_GREATER" ]
        )

        Assert.Equal(Ok(), WorkspaceCompilerPolicy.validateFor 3 net10)
        Assert.Equal(Ok(), WorkspaceCompilerPolicy.validateFor 3 net11)

        // An MSBuild workspace builds for net10.0 alone.
        Assert.True(WorkspaceCompilerPolicy.validate net11 |> Result.isError)

        for version in [ 1; 2 ] do
            Assert.Equal(Ok(), WorkspaceCompilerPolicy.validateFor version net10)
            Assert.True(WorkspaceCompilerPolicy.validateFor version net11 |> Result.isError)

            for symbol in [ "--define:NET11_0"; "--define:NET11_0_OR_GREATER" ] do
                Assert.True(
                    WorkspaceCompilerPolicy.validateFor version (shared @ [ symbol ])
                    |> Result.isError
                )

        // One target, one framework: either net11.0 symbol beside NET10_0 is a mix.
        for mixed in
            [ net11 @ [ "--define:NET10_0" ]
              net10 @ [ "--define:NET11_0" ]
              net10 @ [ "--define:NET11_0_OR_GREATER" ] ] do
            match WorkspaceCompilerPolicy.validateFor 3 mixed with
            | Error message -> Assert.Contains("more than one target framework", message)
            | Ok() -> failwith "A target with the symbols of two frameworks was accepted."

        // A framework no reviewed toolchain produces stays unknown.
        for symbol in [ "--define:NET12_0"; "--define:NET12_0_OR_GREATER"; "--define:NETSTANDARD2_1" ] do
            Assert.True(WorkspaceCompilerPolicy.validateFor 3 (net11 @ [ symbol ]) |> Result.isError)

    [<Fact>]
    let ``the framework assemblies of net11.0 read the catalog and count as the framework`` () =
        let assembly (name: string) (version: string) =
            name
            + ", Version="
            + version
            + ", Culture=neutral, PublicKeyToken=b03f5f7f11d50a3a"

        let approved = "M:System.String.IsNullOrWhiteSpace(System.String)"

        for version in [ "10.0.0.0"; "11.0.0.0" ] do
            Assert.True(SafetyPolicy.approvedIdentity (assembly "System.Runtime" version) approved)
            Assert.Contains(assembly "System.Runtime" version, SafetyPolicy.frameworkIdentities)
            Assert.Contains(assembly "System.Collections" version, SafetyPolicy.frameworkIdentities)

            // The catalog still approves exact signatures only.
            Assert.False(
                SafetyPolicy.approvedIdentity
                    (assembly "System.Runtime" version)
                    "M:System.IO.File.ReadAllText(System.String)"
            )

        // No other version of the framework is reviewed, and no other assembly borrows the entries.
        for version in [ "9.0.0.0"; "10.0.0.1"; "12.0.0.0" ] do
            Assert.False(SafetyPolicy.approvedIdentity (assembly "System.Runtime" version) approved)
            Assert.DoesNotContain(assembly "System.Runtime" version, SafetyPolicy.frameworkIdentities)
            Assert.DoesNotContain(assembly "System.Collections" version, SafetyPolicy.frameworkIdentities)

        Assert.False(SafetyPolicy.approvedIdentity (assembly "System.Collections" "11.0.0.0") approved)

        // The same rule already holds for the two supported FSharp.Core lines.
        for version in [ "10.0.0.0"; "10.1.0.0" ] do
            Assert.True(
                SafetyPolicy.approvedIdentity
                    (assembly "FSharp.Core" version)
                    "M:Microsoft.FSharp.Collections.ListModule.IsEmpty``1(Microsoft.FSharp.Collections.FSharpList{``0})"
            )

    [<Fact>]
    let ``the manifest audit holds a Bazel inventory to the rules of a walked one`` () =
        let audit changed files references =
            fun () -> WorkspaceAudit.validateManifest changed files references

        // The shared source is outside the inventory, and the audit does not look for it there.
        audit policy inventory edges ()

        // Orphan and missing F# sources.
        rejects "ARCH002" (audit policy ("src/Orphan.fs" :: inventory) edges)
        rejects "ARCH002" (audit policy (inventory |> List.filter ((<>) "src/Lib.fs")) edges)

        // Every build file needs a pin, and the inventory must hold one.
        rejects "BUILD005" (audit policy ("tests/BUILD" :: inventory) edges)

        rejects
            "BUILD005"
            (audit
                { policy with
                    Inputs = [ { File = "fdull.json"; Digest = digest } ] }
                inventory
                edges)

        rejects "BUILD005" (audit policy (inventory |> List.filter ((<>) "BUILD.bazel")) edges)
        rejects "BUILD005" (audit policy ("global.json" :: inventory) edges)

        // Other languages need a classification, and a classification must own a file.
        let classified =
            { policy with
                External =
                    Some
                        [ { Path = "tests/Interop.cs"
                            Kind = "implementation"
                            Reason = "The CSharp entry-point tests have their own required checks." } ] }

        rejects "ARCH003" (audit policy ("tests/Interop.cs" :: inventory) edges)
        audit classified ("tests/Interop.cs" :: inventory) edges ()
        rejects "BUILD005" (audit classified inventory edges)

        // The policy's projects are exactly the manifest's.
        rejects "ARCH002" (audit policy inventory (edges @ [ ":extra", [] ]))
        rejects "ARCH002" (audit policy inventory [ ":Lib", [] ])

        // The policy's edges are exactly the ones the invocations show.
        rejects "ARCH001" (audit policy inventory [ ":Lib", []; ":tests", [] ])

        rejects
            "ARCH001"
            (audit
                { policy with
                    Projects = policy.Projects |> List.map (fun project -> { project with References = [] }) }
                inventory
                edges)

        rejects "ARCH004" (audit policy inventory [ ":Lib", [ ":tests" ]; ":tests", [ ":Lib" ] ])

        rejects
            "ARCH002"
            (audit
                { policy with
                    Sources = policy.Sources |> List.map (fun source -> { source with Profile = "TEST" }) }
                inventory
                edges)

        // A manifest never certifies an MSBuild policy, and the MSBuild audit never reads a Bazel one.
        rejects "BUILD003" (audit { policy with Version = 1 } inventory edges)
        rejects "BUILD003" (fun () -> WorkspaceAudit.validate (Path.GetFullPath "missing") policy)

    let private withDirectory action =
        let root =
            Path.Combine(Path.GetTempPath(), "fdull-bazel-" + Guid.NewGuid().ToString("N"))

        Directory.CreateDirectory root |> ignore

        try
            action root
        finally
            Directory.Delete(root, true)

    let private write (root: string) (relative: string) (contents: string) =
        let path = Path.Combine(root, relative)

        Path.GetDirectoryName path
        |> External.required "manifest-tests.parent-directory"
        |> Directory.CreateDirectory
        |> ignore

        File.WriteAllText(path, contents)

    /// Write `changed` as the policy at `root`, with the current fingerprint of each source and input
    /// that exists. A name that leads nowhere keeps its placeholder.
    let private save (root: string) (changed: WorkspacePolicyDocument) =
        let pin (file: string) (current: string) =
            let path = Path.Combine(root, file)

            if File.Exists path then
                SafetyPolicy.fileDigest path
            else
                current

        write
            root
            "fdull.json"
            (Codec.encode
                { changed with
                    Sources =
                        changed.Sources
                        |> List.map (fun source ->
                            { source with
                                Digest = pin source.File source.Digest })
                    Inputs =
                        changed.Inputs
                        |> List.map (fun input ->
                            { input with
                                Digest = pin input.File input.Digest }) })

    /// The workspace `pkg` under an execution root, the entry point it shares, and its policy.
    let private workspace (execroot: string) =
        write execroot "pkg/BUILD.bazel" "# Fixture package.\n"
        write execroot "pkg/src/Lib.fs" "module Lib\n\nlet increment value = value + 1\n"
        write execroot "pkg/tests/LibTests.fs" "module LibTests\n\nlet two = 1 + 1\n"
        write execroot sharedFile sharedText
        save (Path.Combine(execroot, "pkg")) policy

    /// The message that blocks `changed` as the policy at `root`. A well-formed version-three policy
    /// reaches the MSBuild audit, which names the Bazel commands.
    let private validated (root: string) (changed: WorkspacePolicyDocument) =
        save root changed

        match Workspace.validatePolicy root with
        | Error message -> message
        | Ok() -> failwith "A Bazel policy passed the MSBuild audit."

    let private wellFormed =
        "BUILD003: A version-three policy describes a Bazel workspace"

