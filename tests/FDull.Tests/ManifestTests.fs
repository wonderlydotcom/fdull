    let ``the CLI checks a manifest from the execution root and writes its report`` () =
        withWorkspace (fun execroot ->
            let root = Path.Combine(execroot, "pkg")

            let lint (arguments: string list) =
                run execroot ([ cli; "lint"; "pkg"; "--manifest"; "out/relative/manifest.json" ] @ arguments)

            let report () =
                File.ReadAllText(Path.Combine(execroot, "out/report.txt"))

            let passed = lint [ "--report"; "out/report.txt"; "--no-cache" ]
            Assert.True(passed.ExitCode = 0, passed.Error + passed.Output)
            Assert.StartsWith("FDull lint: PASS", passed.Output)
            Assert.Contains("2 projects; 0 reported diagnostics.", passed.Output)
            Assert.Equal(passed.Output, report ())
            Assert.False(Directory.Exists(Path.Combine(root, ".fdull")))

            let reviewed =
                run
                    execroot
                    [ cli
                      "review"
                      "pkg"
                      "--report"
                      "out/report.txt"
                      "--manifest"
                      "out/relative/manifest.json" ]

            Assert.True(reviewed.ExitCode = 0, reviewed.Error + reviewed.Output)
            Assert.StartsWith("FDull review: ADVISORY", reviewed.Output)
            Assert.Equal(reviewed.Output, report ())

            // Text names a file relative to the execution root, inside the workspace or outside it.
            save root { policy with Capabilities = [] }
            let ungranted = lint []
            Assert.Equal(1, ungranted.ExitCode)
            Assert.Contains("\n" + sharedFile + "(3,", ungranted.Output.Replace("\r\n", "\n"))

            seed root
            let failed = lint [ "--report"; "out/report.txt" ]
            Assert.Equal(1, failed.ExitCode)
            Assert.StartsWith("FDull lint: FAIL", failed.Output)
            Assert.Contains("\npkg/src/Lib.fs(4,", failed.Output.Replace("\r\n", "\n"))
            Assert.DoesNotContain(execroot, failed.Output)
            Assert.Equal(failed.Output, report ())

            // JSON keeps the full path.
            let json = lint [ "--format"; "json"; "--report"; "out/report.txt" ]
            Assert.Equal(1, json.ExitCode)
            Assert.Equal(json.Output, report ())

            let diagnostics =
                (Codec.decode<WorkspaceReport> json.Output).Projects
                |> List.collect _.Report.Diagnostics

            Assert.Contains(diagnostics, fun diagnostic -> diagnostic.Rule = "MUT001")

            for diagnostic in diagnostics do
                Assert.True(Path.IsPathRooted diagnostic.File, diagnostic.File)
                Assert.EndsWith("pkg/src/Lib.fs", diagnostic.File.Replace('\\', '/'))

